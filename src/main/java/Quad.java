public class Quad {

    public int x, y;
    public int uvX, uvY;
    public int width, height;

    public Quad( int x, int y, int uvX, int uvY, int width, int height ) {
        this.x = x;
        this.y = y;
        this.uvX = uvX;
        this.uvY = uvY;
        this.width = width;
        this.height = height;
    }
}
